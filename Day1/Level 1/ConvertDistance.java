class ConvertDistance {

    public static void main(String[] args) {

//Distance in kilometers
        double distanceInKm = 10.8;

// Converting distance in  miles
        double distanceInMiles = distanceInKm * 1.6;

// We are printing distance in miles
        System.out.println(" The distance 10.8 km in miles is " + distanceInMiles);

    }

}
